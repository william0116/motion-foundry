export function paletteFor(settings) {
  const preset = schemes.find((s) => s.id === settings.scheme);
  return preset && preset.id !== 'free'
    ? preset
    : {
        id: 'free',
        name: '自由配色',
        surface: '#20272e',
        foreground: '#f5f7f0',
        muted: '#a4afb8',
        border: '#53616b',
        primary: settings.color,
        accent: settings.color,
        tint: '#303b46',
        secondary: settings.color,
        highlight: settings.color,
        buttonText: '#18201b',
      };
}
